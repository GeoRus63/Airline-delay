"""Batch as-of weather feature joins for flight tables.

The helpers preserve every input flight in its original order. METAR uses the
shared five-minute availability/120-minute age contract. TAF selection is a
vectorized as-of bulletin join followed by grouped interval aggregation.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

try:  # package import (tests / notebooks)
    from .prepare_weather import _airport_join_key, match_metar_asof, taf_query_time, noaa_qc_is_eligible
except ImportError:  # direct script-directory import from run_pipeline.py
    from prepare_weather import _airport_join_key, match_metar_asof, taf_query_time, noaa_qc_is_eligible


METAR_FEATURES = [
    "station", "weather_time", "available_at", "availability_assumption", "wind_knots",
    "wind_direction_deg", "gust_knots", "visibility_miles", "ceiling_ft", "ceiling_reported",
    "sky_reported", "precip_amount_in", "precip_measurement_status", "precip_flag", "rain_flag",
    "snow_flag", "weather_codes_reported", "thunder_flag", "temperature_f", "dewpoint_f",
    "relative_humidity", "metar_ambiguous", "metar",
]
TAF_VALUE_FIELDS = ["wind_knots", "wind_direction_deg", "gust_knots", "visibility_miles",
                    "ceiling_ft", "precip_flag", "rain_flag", "snow_flag", "thunder_flag"]

# Model-ready weather numeric whitelist. Audit strings, timestamps and NOAA
# source/QC fields are deliberately excluded. TEMPO and PROB remain separate.
METAR_NUMERIC = [
    "metar_wind_knots", "metar_wind_direction_deg", "metar_gust_knots",
    "metar_visibility_miles", "metar_ceiling_ft", "metar_ceiling_reported",
    "metar_sky_reported", "metar_precip_amount_in", "metar_precip_flag",
    "metar_rain_flag", "metar_snow_flag", "metar_weather_codes_reported",
    "metar_thunder_flag", "metar_temperature_f", "metar_dewpoint_f",
    "metar_relative_humidity", "metar_age_minutes", "metar_missing",
]
TAF_NUMERIC = [
    "taf_bulletin_age_minutes", "taf_lead_minutes", "taf_missing",
    *[f"taf_{kind}_{field}" for kind in ("prevailing", "tempo", "probability")
      for field in (*TAF_VALUE_FIELDS, "segment_count", "missing")],
]

# Only fields with a documented, dimensionally sound mapping are eligible for
# backfill. GHCNh precipitation periods and present-weather mappings are not
# equivalent to IEM p01i/weather codes and intentionally remain unavailable.
NOAA_METAR_FILL_MAP = {
    "metar_temperature_f": ("temperature", "C", "F", "celsius_to_fahrenheit"),
    "metar_dewpoint_f": ("dew_point_temperature", "C", "F", "celsius_to_fahrenheit"),
    "metar_wind_direction_deg": ("wind_direction", "degree", "degree", "identity"),
    "metar_relative_humidity": ("relative_humidity", "%", "%", "identity"),
    "metar_wind_knots": ("wind_speed", "m/s", "knot", "mps_to_knots"),
    "metar_gust_knots": ("wind_gust", "m/s", "knot", "mps_to_knots"),
    "metar_visibility_miles": ("visibility", "km", "mile", "km_to_miles"),
    "metar_ceiling_ft": ("ceiling_height", "m", "ft", "m_to_feet"),
}
# G4a uses wind, gust, visibility and ceiling. A missing gust in an otherwise
# valid METAR commonly means no gust was reported; a missing ceiling can mean
# a valid clear/FEW/SCT sky report. Only fill those fields when their absence
# is consistent with an unavailable whole report, or (for ceiling) an
# explicitly unreported sky condition. Other mapped fields remain available
# for overlap diagnostics, but are not added to the G4a NOAA sensitivity.
NOAA_METAR_FILL_POLICY = {
    "metar_wind_knots": "value_missing",
    "metar_visibility_miles": "value_missing",
    "metar_gust_knots": "whole_metar_missing",
    "metar_ceiling_ft": "whole_metar_missing_or_sky_unreported",
}
NOAA_UNMAPPED_FIELDS = {
    "metar_precip_amount_in": "GHCNh precipitation accumulation period is not equivalent to IEM p01i.",
    "metar_precip_flag": "GHCNh precipitation amount/type codes are not mapped to METAR occurrence flags.",
    "metar_rain_flag": "GHCNh present-weather codes are not mapped to METAR rain codes.",
    "metar_snow_flag": "GHCNh present-weather codes are not mapped to METAR snow codes.",
    "metar_thunder_flag": "No verified GHCNh thunderstorm-to-METAR mapping is implemented.",
}


def augment_metar(flights, metar_observations, *, airport_col="airport_id",
                  prediction_col="prediction_time", max_age=pd.Timedelta(minutes=120)):
    """Return a flight-preserving frame with observed-weather columns prefixed metar_."""
    joined = match_metar_asof(flights, metar_observations, airport_col=airport_col,
                              prediction_col=prediction_col, max_age=max_age)
    rename = {column: f"metar_{column}" for column in METAR_FEATURES if column in joined.columns}
    rename["metar_candidate_weather_time"] = "metar_candidate_weather_time"
    # Diagnostics generated by the shared matcher already have their final names.
    return joined.rename(columns=rename).drop(columns=[f"{airport_col}_metar"], errors="ignore")


def _as_utc(series):
    parsed = pd.to_datetime(series, utc=True, errors="coerce")
    if isinstance(parsed, pd.Series):
        return parsed.dt.as_unit("ns")
    if isinstance(parsed, pd.DatetimeIndex):
        return parsed.as_unit("ns")
    if isinstance(parsed, pd.Timestamp) and pd.notna(parsed):
        return parsed.as_unit("ns")
    return parsed


def _safe_bool(series):
    if series.dtype == bool:
        return series.fillna(False)
    return series.astype("string").str.lower().isin(["true", "1", "yes"])


def _numeric_array(series):
    return pd.to_numeric(series, errors="coerce").to_numpy(dtype="float64", na_value=np.nan)


def _noaa_with_airports(noaa, airports, airport_col="airport_id"):
    required_airports = {airport_col, "ghcnh_id"}
    if required_airports - set(airports.columns):
        raise ValueError(f"airports table needs columns {sorted(required_airports)}")
    if "STATION" not in noaa:
        raise ValueError("NOAA table needs the GHCNh STATION column")
    data = noaa.copy()
    if "observation_time" in data:
        data["observation_time"] = _as_utc(data.observation_time)
    elif "DATE" in data:
        data["observation_time"] = _as_utc(data.DATE)
    else:
        raise ValueError("NOAA table needs observation_time or DATE")
    data["_noaa_station_key"] = data.STATION.astype("string").str.strip()
    mapping = airports[[airport_col, "ghcnh_id"]].dropna().copy()
    mapping["_noaa_station_key"] = mapping.ghcnh_id.astype("string").str.strip()
    mapping["_airport_key"] = _airport_join_key(mapping[airport_col])
    mapping = mapping[["_noaa_station_key", "_airport_key", airport_col]].drop_duplicates()
    ambiguous_stations = mapping.groupby("_noaa_station_key")._airport_key.nunique()
    ambiguous_stations = ambiguous_stations[ambiguous_stations.gt(1)].index
    mapping = mapping.loc[~mapping._noaa_station_key.isin(ambiguous_stations)]
    data = data.merge(mapping, on="_noaa_station_key", how="inner", validate="many_to_one")
    return data


def _noaa_field_candidates(noaa_airports, target, lag_minutes):
    element, native_unit, target_unit, conversion = NOAA_METAR_FILL_MAP[target]
    if element not in noaa_airports:
        return pd.DataFrame()
    value = pd.to_numeric(noaa_airports[element], errors="coerce")
    if conversion == "celsius_to_fahrenheit":
        value = value * (9.0 / 5.0) + 32.0
    elif conversion == "mps_to_knots":
        value = value * 1.943844
    elif conversion == "km_to_miles":
        value = value / 1.609344
    elif conversion == "m_to_feet":
        value = value / 0.3048

    eligible_col = f"{element}_qc_eligible"
    source_col = f"{element}_Source_Code"
    quality_col = f"{element}_Quality_Code"
    if eligible_col in noaa_airports:
        eligible = _safe_bool(noaa_airports[eligible_col])
    elif source_col in noaa_airports and quality_col in noaa_airports:
        eligible = pd.Series([
            noaa_qc_is_eligible(source, quality, element)
            for source, quality in zip(noaa_airports[source_col], noaa_airports[quality_col])
        ], index=noaa_airports.index, dtype=bool)
    else:
        return pd.DataFrame()

    records = noaa_airports.loc[eligible & value.notna()].copy()
    if records.empty:
        return pd.DataFrame()
    records["_noaa_value"] = value.loc[records.index]
    # No version/receipt time is present in GHCNh: conflicting eligible values
    # for one station/time are excluded rather than choosing the fullest row.
    distinct = records.groupby(["_airport_key", "observation_time"])["_noaa_value"].transform("nunique")
    records = records.loc[distinct.le(1)].copy()
    if records.empty:
        return pd.DataFrame()
    records["_noaa_available_at"] = records.observation_time + pd.Timedelta(minutes=lag_minutes)
    records["_noaa_source_code"] = records.get(source_col, pd.Series(pd.NA, index=records.index)).astype("string")
    records["_noaa_quality_code"] = records.get(quality_col, pd.Series(pd.NA, index=records.index)).astype("string")
    records["_noaa_station"] = records.STATION.astype("string")
    records["_noaa_source_file"] = records.get("source_file", pd.Series(pd.NA, index=records.index)).astype("string")
    records = records.sort_values(["_airport_key", "observation_time", "_noaa_source_code"], kind="stable")
    records = records.drop_duplicates(["_airport_key", "observation_time"], keep="first")
    return records[["_airport_key", "observation_time", "_noaa_available_at", "_noaa_value",
                    "_noaa_source_code", "_noaa_quality_code", "_noaa_station", "_noaa_source_file"]]


def _merge_noaa_candidate(left, candidates, *, prediction_col, max_age, lag):
    if candidates.empty or left.empty:
        return left.assign(_noaa_observation_time=pd.NaT, _noaa_available_at=pd.NaT,
                           _noaa_value=np.nan, _noaa_source_code=pd.NA, _noaa_quality_code=pd.NA,
                           _noaa_station=pd.NA, _noaa_source_file=pd.NA)
    right = candidates
    valid = left[prediction_col].notna() & left._airport_key.notna()
    valid_left = left.loc[valid].sort_values(prediction_col)
    invalid_left = left.loc[~valid].copy()
    max_age_delta = (pd.Timedelta(minutes=max_age) if isinstance(max_age, (int, float, np.integer, np.floating))
                     else pd.Timedelta(max_age))
    if not valid_left.empty:
        joined = pd.merge_asof(
            valid_left, right.sort_values("_noaa_available_at"),
            left_on=prediction_col, right_on="_noaa_available_at", by="_airport_key",
            direction="backward", tolerance=max_age_delta + pd.Timedelta(minutes=lag),
        )
        joined = joined.rename(columns={"observation_time": "_noaa_observation_time"})
    else:
        joined = valid_left.copy()
    if not invalid_left.empty:
        for col in ("_noaa_observation_time", "_noaa_available_at"):
            invalid_left[col] = pd.NaT
        for col in ("_noaa_value", "_noaa_source_code", "_noaa_quality_code", "_noaa_station", "_noaa_source_file"):
            invalid_left[col] = pd.NA if col != "_noaa_value" else np.nan
        joined = pd.concat([joined, invalid_left], ignore_index=False, sort=False)
    age = (joined[prediction_col] - joined._noaa_observation_time).dt.total_seconds() / 60
    joined["_noaa_age_minutes"] = age
    joined.loc[age.gt(max_age_delta.total_seconds() / 60), "_noaa_value"] = np.nan
    return joined


def augment_noaa(frame, noaa, airports, lag_minutes=5, max_age_minutes=120, *,
                 airport_col="airport_id", prediction_col="prediction_time"):
    """Sensitivity backfill of missing IEM METAR values from eligible GHCNh.

    NOAA observations become available at observation_time + lag_minutes. This
    is an explicit retrospective sensitivity assumption, not verified live
    availability. Only missing numeric METAR fields with explicit unit maps are
    filled; IEM values always win. Audit provenance is emitted per field.
    """
    required = {airport_col, prediction_col}
    if required - set(frame.columns):
        raise ValueError(f"flight weather frame missing columns: {sorted(required - set(frame.columns))}")
    original_index = frame.index
    result = frame.copy()
    result["_noaa_original_index"] = list(original_index)
    result["_noaa_row"] = np.arange(len(result), dtype="int64")
    result = result.set_index("_noaa_row", drop=False)
    result["_airport_key"] = _airport_join_key(result[airport_col])
    result[prediction_col] = _as_utc(result[prediction_col])
    noaa_airports = _noaa_with_airports(noaa, airports, airport_col=airport_col)
    fill_counts = {}
    for target in NOAA_METAR_FILL_MAP:
        if target not in result:
            raise ValueError(f"METAR feature frame lacks required destination column: {target}")
        source_marker = f"{target}_source"
        age_col = f"{target}_noaa_age_minutes"
        time_col = f"{target}_noaa_observation_time"
        station_col = f"{target}_noaa_station"
        source_code_col = f"{target}_noaa_source_code"
        quality_col = f"{target}_noaa_quality_code"
        file_col = f"{target}_noaa_source_file"
        for column in (source_marker, age_col, time_col, station_col, source_code_col, quality_col, file_col):
            if column not in result:
                result[column] = pd.NA
        original = pd.to_numeric(result[target], errors="coerce")
        result[target] = original
        if result[source_marker].isna().any():
            result.loc[original.notna() & result[source_marker].isna(), source_marker] = "IEM"
        missing_mask = original.isna()
        fill_counts[target] = 0
        policy = NOAA_METAR_FILL_POLICY.get(target)
        if policy is None:
            continue  # retained in NOAA overlap diagnostics, outside G4a fill
        whole_metar_missing = (
            _safe_bool(result["metar_missing"])
            if "metar_missing" in result
            else pd.Series(False, index=result.index, dtype=bool)
        )
        # augment_metar prefixes the source feature name, so its ambiguity
        # flag is currently `metar_metar_ambiguous`; accept the unprefixed
        # matcher form too for direct callers. Conflicting reports are never a
        # NOAA-fill opportunity, even though the matcher marks them missing.
        ambiguous_col = next((column for column in
                              ("metar_metar_ambiguous", "metar_ambiguous")
                              if column in result), None)
        ambiguous = (_safe_bool(result[ambiguous_col]) if ambiguous_col
                     else pd.Series(False, index=result.index, dtype=bool))
        whole_metar_missing &= ~ambiguous
        if "metar_missing_reason" in result:
            whole_metar_missing &= result.metar_missing_reason.isin(
                ["no_observation", "stale_observation"])
        missing_mask &= ~ambiguous
        if policy == "whole_metar_missing":
            missing_mask &= whole_metar_missing
        elif policy == "whole_metar_missing_or_sky_unreported":
            sky_unreported = (
                pd.to_numeric(result["metar_sky_reported"], errors="coerce").eq(0)
                if "metar_sky_reported" in result
                else pd.Series(False, index=result.index, dtype=bool)
            )
            missing_mask &= whole_metar_missing | sky_unreported
        element, native_unit, target_unit, conversion = NOAA_METAR_FILL_MAP[target]
        candidates = _noaa_field_candidates(noaa_airports, target, lag_minutes)
        if not missing_mask.any() or candidates.empty:
            continue
        left = result.loc[missing_mask, ["_noaa_row", "_airport_key", prediction_col]].copy()
        joined = _merge_noaa_candidate(left, candidates, prediction_col=prediction_col,
                                       max_age=max_age_minutes, lag=lag_minutes)
        joined = joined.set_index("_noaa_row").reindex(
            result.loc[missing_mask, "_noaa_row"].to_numpy())
        row_ids = joined.index
        # Keep diagnostics for the selected qualified candidate, even if it is
        # just beyond the permitted age; only in-range candidates may fill.
        for output_col, source in [(age_col, "_noaa_age_minutes"), (time_col, "_noaa_observation_time"),
                                   (station_col, "_noaa_station"), (source_code_col, "_noaa_source_code"),
                                   (quality_col, "_noaa_quality_code"), (file_col, "_noaa_source_file")]:
            result.loc[row_ids, output_col] = joined[source].to_numpy()
        age = pd.to_numeric(joined._noaa_age_minutes, errors="coerce")
        value = pd.to_numeric(joined._noaa_value, errors="coerce")
        eligible_fill = value.notna() & age.between(0, max_age_minutes, inclusive="both")
        fill_rows = row_ids[eligible_fill.to_numpy()]
        if len(fill_rows):
            result.loc[fill_rows, target] = value.loc[eligible_fill].to_numpy()
            result.loc[fill_rows, source_marker] = "GHCNh"
            fill_counts[target] = len(fill_rows)
    source_cols = [f"{target}_source" for target in NOAA_METAR_FILL_MAP]
    result["metar_noaa_missing"] = (~result[source_cols].eq("GHCNh").any(axis=1)).astype("int8")
    observed_value_cols = [column for column in [
        *NOAA_METAR_FILL_MAP.keys(), "metar_precip_amount_in", "metar_precip_flag",
        "metar_rain_flag", "metar_snow_flag", "metar_thunder_flag", "metar_relative_humidity",
    ] if column in result]
    result["metar_missing"] = result[observed_value_cols].isna().all(axis=1).astype("int8")
    if "metar_missing_flag" in result:
        result["metar_missing_flag"] = result.metar_missing
    result = result.sort_index()
    restored_index = result.pop("_noaa_original_index").tolist()
    result = result.drop(columns=["_noaa_row", "_airport_key"])
    result.index = pd.Index(restored_index, name=original_index.name)
    result.attrs["noaa_fill_counts"] = fill_counts
    result.attrs["noaa_fill_assumption"] = (
        f"GHCNh observation_time + {lag_minutes} minutes; retrospective sensitivity only; "
        "historical receipt availability not verified")
    result.attrs["noaa_qc_limitation"] = (
        "Only exact documented source/Quality_Code pairs are accepted. GHCNh documents both "
        "post-integration QC and component-source QC but does not specify their serialization/precedence "
        "in the single per-element Quality_Code field; this branch is a sensitivity analysis, not full-QC certification.")
    result.attrs["noaa_unmapped_fields"] = NOAA_UNMAPPED_FIELDS.copy()
    return result


def noaa_overlap_diagnostics(metar_observations, noaa, airports, *, airport_col="airport_id"):
    """Compare exact airport/time overlaps without using any flight labels."""
    needed = {airport_col, "station", "weather_time"}
    if needed - set(metar_observations.columns):
        raise ValueError(f"METAR observations missing columns: {sorted(needed - set(metar_observations.columns))}")
    noaa_airports = _noaa_with_airports(noaa, airports, airport_col=airport_col)
    metar = metar_observations.copy()
    metar["weather_time"] = _as_utc(metar.weather_time)
    metar["_airport_key"] = _airport_join_key(metar[airport_col])
    if "metar_ambiguous" in metar:
        metar = metar.loc[~_safe_bool(metar.metar_ambiguous)]
    detail = []
    summary = []
    for target, (element, native_unit, target_unit, conversion) in NOAA_METAR_FILL_MAP.items():
        candidates = _noaa_field_candidates(noaa_airports, target, lag_minutes=0)
        metar_column = target.removeprefix("metar_")
        if candidates.empty or metar_column not in metar:
            summary.append({"feature": target, "overlap_count": 0, "mean_signed_difference": np.nan,
                            "mean_absolute_difference": np.nan, "max_absolute_difference": np.nan,
                            "metar_unit": target_unit, "noaa_native_unit": native_unit,
                            "conversion": conversion, "unit_consistency": "no_exact_overlap"})
            continue
        right = candidates.rename(columns={"_airport_key": "_noaa_airport_key",
                                          "observation_time": "weather_time",
                                          "_noaa_value": "noaa_converted_value",
                                          "_noaa_source_code": "noaa_source_code",
                                          "_noaa_quality_code": "noaa_quality_code",
                                          "_noaa_station": "noaa_station"})
        joined = metar[["_airport_key", "weather_time", "station", metar_column]].merge(
            right[["_noaa_airport_key", "weather_time", "noaa_converted_value", "noaa_source_code",
                   "noaa_quality_code", "noaa_station"]],
            left_on=["_airport_key", "weather_time"], right_on=["_noaa_airport_key", "weather_time"],
            how="inner", validate="many_to_many")
        joined[metar_column] = pd.to_numeric(joined[metar_column], errors="coerce")
        joined = joined.loc[joined[metar_column].notna()].copy()
        joined["difference_noaa_minus_metar"] = joined.noaa_converted_value - joined[metar_column]
        joined["absolute_difference"] = joined.difference_noaa_minus_metar.abs()
        joined["feature"] = target
        joined["metar_unit"] = target_unit
        joined["noaa_native_unit"] = native_unit
        joined["conversion"] = conversion
        joined["match_basis"] = "airport ghcnh_id mapping and exact UTC observation timestamp"
        detail.append(joined.rename(columns={metar_column: "metar_value"}))
        diffs = joined.difference_noaa_minus_metar.dropna()
        summary.append({"feature": target, "overlap_count": int(diffs.size),
                        "mean_signed_difference": float(diffs.mean()) if len(diffs) else np.nan,
                        "mean_absolute_difference": float(diffs.abs().mean()) if len(diffs) else np.nan,
                        "max_absolute_difference": float(diffs.abs().max()) if len(diffs) else np.nan,
                        "metar_unit": target_unit, "noaa_native_unit": native_unit,
                        "conversion": conversion,
                        "unit_consistency": "converted_for_comparison" if len(diffs) else "no_numeric_overlap"})
    detail_frame = pd.concat(detail, ignore_index=True) if detail else pd.DataFrame()
    return {"pairs": detail_frame, "summary": pd.DataFrame(summary)}


def _reduce_active(values, active, reduction):
    values = _numeric_array(values)
    valid = active & np.isfinite(values)[None, :]
    fill = -np.inf if reduction == "max" else np.inf
    masked = np.where(valid, values[None, :], fill)
    result = masked.max(axis=1) if reduction == "max" else masked.min(axis=1)
    result[~np.isfinite(result)] = np.nan
    return result


def _aggregate_segment_kind(query_ns, segments, kind):
    if segments.empty:
        return None
    starts = segments.segment_start.astype("int64").to_numpy()
    ends = segments.segment_end.astype("int64").to_numpy()
    active = (query_ns[:, None] >= starts[None, :]) & (query_ns[:, None] < ends[None, :])
    count = active.sum(axis=1)
    result = {f"taf_{kind}_segment_count": count}
    # Concurrent conditions are summarized conservatively: maximum wind/gust,
    # minimum visibility/ceiling, and any-occurrence flags. Direction comes
    # from the active segment with the latest start time.
    for source, output, reduction in [
        ("wind_knots", "wind_knots", "max"),
        ("gust_knots", "gust_knots", "max"),
        ("visibility_miles", "visibility_miles", "min"),
        ("ceiling_ft", "ceiling_ft", "min"),
        ("precip_flag", "precip_flag", "max"),
        ("rain_flag", "rain_flag", "max"),
        ("snow_flag", "snow_flag", "max"),
        ("thunder_flag", "thunder_flag", "max"),
    ]:
        if source in segments:
            result[f"taf_{kind}_{output}"] = _reduce_active(segments[source], active, reduction)
        else:
            result[f"taf_{kind}_{output}"] = np.full(len(query_ns), np.nan)
    if "wind_direction_deg" in segments:
        latest_start = np.where(active, starts[None, :], -1).max(axis=1)
        direction = _numeric_array(segments.wind_direction_deg)
        vals = np.full(len(query_ns), np.nan)
        latest_idx = np.where(active & (starts[None, :] == latest_start[:, None]),
                              np.arange(len(starts))[None, :], -1).max(axis=1)
        valid = latest_idx >= 0
        vals[valid] = direction[latest_idx[valid]]
        result[f"taf_{kind}_wind_direction_deg"] = vals
    else:
        result[f"taf_{kind}_wind_direction_deg"] = np.full(len(query_ns), np.nan)
    result[f"taf_{kind}_missing"] = (count == 0).astype("int8")
    for field, fn in [("segment_start_min", np.min), ("segment_end_max", np.max)]:
        times = starts if field == "segment_start_min" else ends
        fill = np.iinfo("int64").max if field == "segment_start_min" else np.iinfo("int64").min
        masked = np.where(active, times[None, :], fill)
        vals = fn(masked, axis=1)
        vals[count == 0] = pd.NaT.value
        result[f"taf_{kind}_{field}"] = pd.to_datetime(vals, utc=True)
    return result


def augment_taf(flights, taf_segments, taf_bulletins, *, airport_col="airport_id",
                 scheduled_dep_col="scheduled_dep_utc", prediction_col="prediction_time",
                 allow_unverified_revisions=False):
    """Add as-of prevailing, TEMPO, and probability TAF features in batches.

    Bulletin versions are selected once with a grouped merge_asof. Each chosen
    airport/product group then uses vectorized interval masks; the function
    does not call the row-oriented select_taf_asof helper.
    """
    original_index = flights.index
    work = flights.copy()
    work["_taf_row"] = np.arange(len(work), dtype="int64")
    work["_taf_original_index"] = list(original_index)
    work["_taf_airport_key"] = _airport_join_key(work[airport_col])
    work["_taf_decision_time"] = _as_utc(work[prediction_col])
    work["_taf_query_time"] = taf_query_time(
        work, scheduled_dep_col=scheduled_dep_col, prediction_col=prediction_col)

    bulletins = taf_bulletins.copy()
    required = {airport_col, "product_id", "status", "message_type", "availability_time"}
    missing = required - set(bulletins.columns)
    if missing:
        raise ValueError(f"TAF bulletin table missing columns: {sorted(missing)}")
    bulletins["_taf_airport_key"] = _airport_join_key(bulletins[airport_col])
    bulletins["product_id"] = bulletins.product_id.astype("string")
    for column in ("availability_time", "archive_issue_time", "body_issue_time"):
        if column in bulletins:
            bulletins[column] = _as_utc(bulletins[column])
        else:
            bulletins[column] = pd.NaT
    if "issue_time_mismatch_minutes" not in bulletins:
        bulletins["issue_time_mismatch_minutes"] = np.nan
    if "availability_assumption" not in bulletins:
        bulletins["availability_assumption"] = "availability_proxy_unlabeled"
    bulletins["_taf_same_time_count"] = bulletins.groupby(
        ["_taf_airport_key", "availability_time"], dropna=False).product_id.transform("nunique")

    meta_columns = ["product_id", "status", "message_type", "availability_time", "archive_issue_time",
                    "body_issue_time", "issue_time_mismatch_minutes", "availability_assumption",
                    "_taf_same_time_count"]
    rename_meta = {
        "product_id": "taf_product_id", "status": "taf_bulletin_status", "message_type": "taf_message_type",
        "availability_time": "taf_available_at", "archive_issue_time": "taf_archive_issue_time",
        "body_issue_time": "taf_body_issue_time", "issue_time_mismatch_minutes": "taf_issue_time_mismatch_minutes",
        "availability_assumption": "taf_availability_assumption", "_taf_same_time_count": "_taf_same_time_count",
    }
    right = bulletins[["_taf_airport_key", *meta_columns]].rename(columns=rename_meta)
    right = right.dropna(subset=["taf_available_at", "_taf_airport_key"])
    valid_left_mask = work._taf_decision_time.notna() & work._taf_airport_key.notna()
    valid_left = work.loc[valid_left_mask].sort_values("_taf_decision_time")
    if not right.empty and not valid_left.empty:
        selected = pd.merge_asof(valid_left, right.sort_values("taf_available_at"),
                                 left_on="_taf_decision_time", right_on="taf_available_at",
                                 by="_taf_airport_key", direction="backward", suffixes=("", "_bulletin"))
    else:
        selected = valid_left.copy()
        for column in rename_meta.values():
            if column not in selected:
                selected[column] = pd.NaT if column.endswith("_at") or column.endswith("_time") else pd.NA
    invalid_left = work.loc[~valid_left_mask].copy()
    for column in rename_meta.values():
        if column not in invalid_left:
            invalid_left[column] = pd.NaT if column.endswith("_at") or column.endswith("_time") else pd.NA
    work = pd.concat([selected, invalid_left], ignore_index=False, sort=False).sort_values("_taf_row")

    # Detect a potentially newer archive bulletin whose body timestamp is
    # absent. It blocks using an older timed version, without inventing an
    # availability time for the untimed bulletin.
    untimed = bulletins.loc[bulletins.availability_time.isna() & bulletins.archive_issue_time.notna(),
                            ["_taf_airport_key", "archive_issue_time"]].rename(
                                columns={"archive_issue_time": "taf_untimed_archive_issue_time"})
    valid_probe_mask = work._taf_decision_time.notna() & work._taf_airport_key.notna()
    if not untimed.empty and valid_probe_mask.any():
        probes = work.loc[valid_probe_mask, ["_taf_row", "_taf_airport_key", "_taf_decision_time"]].sort_values(
            "_taf_decision_time")
        latest_untimed = pd.merge_asof(probes, untimed.sort_values("taf_untimed_archive_issue_time"),
            left_on="_taf_decision_time", right_on="taf_untimed_archive_issue_time",
            by="_taf_airport_key", direction="backward")
        work = work.merge(latest_untimed[["_taf_row", "taf_untimed_archive_issue_time"]],
                          on="_taf_row", how="left", validate="one_to_one")
    else:
        work["taf_untimed_archive_issue_time"] = pd.NaT

    work["taf_query_time"] = work._taf_query_time
    work = work.sort_values("_taf_row").set_index("_taf_row", drop=False)
    # merge_asof can leave timezone columns as object when the right side is
    # entirely empty or has mixed missing values. Normalize before arithmetic.
    for column in ("taf_available_at", "taf_archive_issue_time", "taf_body_issue_time",
                   "taf_untimed_archive_issue_time"):
        if column in work:
            work[column] = _as_utc(work[column])
    work["taf_bulletin_age_minutes"] = (work._taf_decision_time - work.taf_available_at).dt.total_seconds() / 60
    work["taf_lead_minutes"] = (work._taf_query_time - work.taf_available_at).dt.total_seconds() / 60
    work["taf_status"] = "no_available_bulletin"
    has_product = work.taf_product_id.notna()
    work.loc[has_product, "taf_status"] = "outside_validity"
    status_text = work.taf_bulletin_status.astype("string").str.lower()
    work.loc[has_product & status_text.isin(["cancelled", "canceled", "nil"]), "taf_status"] = status_text
    work.loc[has_product & status_text.eq("ambiguous"), "taf_status"] = "ambiguous_bulletin"
    revision_disabled = work.taf_message_type.astype("string").isin(["amended", "corrected", "delayed"])
    if allow_unverified_revisions:
        revision_disabled = pd.Series(False, index=work.index)
    work.loc[has_product & ~status_text.isin(["cancelled", "canceled", "nil", "ambiguous"]) & revision_disabled,
             "taf_status"] = "disabled_revision"
    work.loc[has_product & work._taf_same_time_count.fillna(0).gt(1), "taf_status"] = "ambiguous_bulletin"
    timed_before_candidate = work.taf_available_at.notna()
    untimed_newer = work.taf_untimed_archive_issue_time.notna() & (
        work.taf_available_at.isna() | work.taf_untimed_archive_issue_time.ge(work.taf_available_at))
    work.loc[untimed_newer, "taf_status"] = "unverified_issue_time"
    usable = work.taf_status.eq("outside_validity") & timed_before_candidate & status_text.eq("normal")
    # Accumulate positional outputs once, avoiding millions of DataFrame writes.
    # Bulletin selection and segment aggregation retain the same semantics.
    buffers = {}
    time_fields = set()
    for kind in ("prevailing", "tempo", "probability"):
        buffers[f"taf_{kind}_missing"] = np.ones(len(work), dtype="int64")
    for kind in ("prevailing", "tempo", "probability"):
        buffers[f"taf_{kind}_segment_count"] = np.zeros(len(work), dtype="int64")
    for kind in ("prevailing", "tempo", "probability"):
        for field in (*TAF_VALUE_FIELDS, "segment_start_min", "segment_end_max"):
            name = f"taf_{kind}_{field}"
            if field.endswith("_min") or field.endswith("_max"):
                buffers[name] = np.full(len(work), pd.NaT.value, dtype="int64")
                time_fields.add(name)
            else:
                buffers[name] = np.full(len(work), np.nan)
    status_buffer = work.taf_status.to_numpy(dtype=object, copy=True)
    if usable.any() and not taf_segments.empty:
        segments = taf_segments.copy()
        segments["_taf_airport_key"] = _airport_join_key(segments[airport_col])
        segments["product_id"] = segments.product_id.astype("string")
        segments["segment_start"] = _as_utc(segments.segment_start)
        segments["segment_end"] = _as_utc(segments.segment_end)
        if "interval_usable" in segments:
            segments = segments.loc[_safe_bool(segments.interval_usable)]
        segments = segments.dropna(subset=["segment_start", "segment_end", "_taf_airport_key", "product_id"])
        segments = segments.loc[segments.segment_end.gt(segments.segment_start)]
        selected_keys = work.loc[usable, ["_taf_airport_key", "taf_product_id"]].drop_duplicates()
        segments = segments.merge(selected_keys, left_on=["_taf_airport_key", "product_id"],
                                  right_on=["_taf_airport_key", "taf_product_id"], how="inner")
        if "ftype" not in segments:
            segments["ftype"] = ""
        ftype = segments.ftype.astype("string").str.lower()
        tempo_flag = _safe_bool(segments.is_tempo) if "is_tempo" in segments else pd.Series(False, index=segments.index)
        prob_flag = _safe_bool(segments.is_probability) if "is_probability" in segments else pd.Series(False, index=segments.index)
        prob_flag = prob_flag | ftype.str.contains("prob", regex=False).fillna(False)
        tempo_flag = (tempo_flag | ftype.eq("temporary").fillna(False)) & ~prob_flag
        segments["_taf_kind"] = np.select(
            [prob_flag, tempo_flag, ftype.isin(["observation", "forecast"])],
            ["probability", "tempo", "prevailing"], default="other")
        segments = segments.loc[segments._taf_kind.ne("other")]
        seg_groups = segments.groupby(["_taf_airport_key", "product_id", "_taf_kind"], sort=False)
        active_rows = work.loc[usable].set_index("_taf_row", drop=False)
        for (airport_key, product_id), flight_group in active_rows.groupby(
                ["_taf_airport_key", "taf_product_id"], sort=False):
            query = flight_group._taf_query_time
            valid_query = query.notna()
            if not valid_query.any():
                continue
            row_ids = flight_group.index[valid_query]
            query_ns = query.loc[valid_query].astype("int64").to_numpy()
            any_active = np.zeros(len(row_ids), dtype=bool)
            for kind in ("prevailing", "tempo", "probability"):
                try:
                    group = seg_groups.get_group((airport_key, product_id, kind))
                except KeyError:
                    continue
                aggregate = _aggregate_segment_kind(query_ns, group, kind)
                counts = aggregate[f"taf_{kind}_segment_count"]
                active_kind = counts > 0
                any_active |= active_kind
                buffers[f"taf_{kind}_missing"][row_ids] = (counts == 0).astype("int8")
                buffers[f"taf_{kind}_segment_count"][row_ids] = counts
                for field, values in aggregate.items():
                    if field == f"taf_{kind}_segment_count" or field == f"taf_{kind}_missing":
                        continue
                    buffers[field][row_ids] = values.asi8 if field in time_fields else values
            status_buffer[row_ids[any_active]] = "matched"

    for field, values in buffers.items():
        work[field] = pd.to_datetime(values, unit="ns", utc=True) if field in time_fields else values
    work["taf_status"] = pd.Series(status_buffer, index=work.index, dtype=work.taf_status.dtype)
    work["taf_missing"] = (~work.taf_status.eq("matched")).astype("int8")
    work = work.sort_index()
    original = work.pop("_taf_original_index").tolist()
    internal = [column for column in work.columns if column.startswith("_taf_") and column not in {
        "_taf_row", "_taf_airport_key", "_taf_decision_time", "_taf_query_time"}]
    work = work.drop(columns=internal + ["_taf_row", "_taf_airport_key", "_taf_decision_time", "_taf_query_time"],
                     errors="ignore")
    work.index = pd.Index(original, name=original_index.name)
    return work
